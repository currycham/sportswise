def prescribe(name, minutes, technique, sets, reps, rest, intensity, *, alternatives=True):
    benefit, watch, other = DETAILS[name]
    options = []
    if alternatives and other:
        options.append(prescribe(other, minutes, DETAILS[other][1], sets, reps, rest,
                                 '轻松 · 组末至少留 4 次余力', alternatives=False))
    return {'title':name,'minutes':minutes,'detail':technique,'kind':'move',
            'sets':sets,'reps':reps,'each_side':name in SINGLE_SIDE,'rest_seconds':rest,
            'intensity':intensity,'tempo':'用力约 1 秒，回程约 2 秒',
            'benefit':benefit,'caution':watch+' 出现新发疼痛或动作失控时停止。','alternatives':options}
